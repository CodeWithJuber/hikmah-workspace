#!/usr/bin/env node
/** Sign the curated seed manifests and emit the migration seed block.
 *
 * Owner tooling (PR-26). For each directory in connectors/ holding a
 * manifest.json, this validates the manifest, signs its canonical bytes with
 * the owner's Ed25519 signing key, and writes the manifest back with
 * `signature` and `signer` attached. It then prints the SQL INSERT block to
 * paste into the catalog migration, so the database seed is byte-identical
 * to the reviewed manifest files.
 *
 * Key custody is the owner's job: the private key is read from
 * $CATALOG_SIGNING_KEY (base64 PKCS#8 DER), then ~/.config/hikmah/catalog-signing.key,
 * then ~/workspace/catalog-signing.key (dev fallback). It is never committed.
 * The matching public key is committed at connectors/catalog.pub, which is
 * what the routes and tests verify against.
 *
 * Run: node scripts/seed-catalog.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { validateManifest } from '../lib/catalog/manifest.ts';
import { signManifest, fingerprint, verifyManifest } from '../lib/catalog/signing.ts';

const ROOT = resolve(import.meta.dirname, '..');
const CONNECTORS = join(ROOT, 'connectors');

function loadPrivateKey() {
  if (process.env.CATALOG_SIGNING_KEY) return process.env.CATALOG_SIGNING_KEY.trim();
  for (const candidate of [
    join(homedir(), '.config', 'hikmah', 'catalog-signing.key'),
    join(homedir(), 'workspace', 'catalog-signing.key'),
  ]) {
    if (existsSync(candidate)) return readFileSync(candidate, 'utf8').trim();
  }
  console.error(
    'No signing key: set $CATALOG_SIGNING_KEY or place the key at ~/.config/hikmah/catalog-signing.key',
  );
  process.exit(1);
}

const { createPrivateKey, createPublicKey } = await import('node:crypto');
const privateKeyB64 = loadPrivateKey();
const privateKey = createPrivateKey({
  key: Buffer.from(privateKeyB64, 'base64'),
  format: 'der',
  type: 'pkcs8',
});
const publicKey = createPublicKey(privateKey);
const signerB64 = publicKey.export({ format: 'der', type: 'spki' }).toString('base64');
console.error(`signer fingerprint: ${fingerprint(signerB64)}`);

const names = readdirSync(CONNECTORS, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const inserts = [];
for (const name of names) {
  const path = join(CONNECTORS, name, 'manifest.json');
  if (!existsSync(path)) continue;
  const raw = JSON.parse(readFileSync(path, 'utf8'));
  // Strip a previous signature before re-signing: the signature covers the
  // unsigned manifest, never itself.
  const unsigned = { ...raw };
  delete unsigned.signature;
  delete unsigned.signer;
  const validated = validateManifest(unsigned);
  if (!validated.ok) {
    console.error(`Refusing to sign ${name}:`, validated.errors);
    process.exit(1);
  }
  const manifest = validated.manifest;
  const sig = signManifest(manifest, privateKeyB64);
  if (!verifyManifest(manifest, sig, signerB64)) {
    console.error(`Self-check failed for ${name}: signature does not verify.`);
    process.exit(1);
  }
  const signed = { ...manifest, signature: sig, signer: signerB64 };
  writeFileSync(path, JSON.stringify(signed, null, 2) + '\n');
  const id = `${manifest.name}@${manifest.version}`;
  const manifestJson = JSON.stringify(manifest).replace(/'/g, "''");
  inserts.push(
    `INSERT INTO connector_manifests (id, name, version, manifest_json, signature, signer, status, created_at, updated_at)\n` +
      `VALUES ('${id}', '${manifest.name}', '${manifest.version}', '${manifestJson}',\n` +
      `        '${sig}', '${signerB64}', 'active', '2026-09-30T00:00:00.000Z', '2026-09-30T00:00:00.000Z')\n` +
      `ON CONFLICT (id) DO NOTHING;`,
  );
  for (const permission of manifest.permissions) {
    inserts.push(
      `INSERT INTO connector_permissions (manifest_id, permission)\nVALUES ('${id}', '${permission}')\nON CONFLICT (manifest_id, permission) DO NOTHING;`,
    );
  }
  console.error(`signed ${id}`);
}

console.log(
  '-- Seed: curated catalog manifests (generated by scripts/seed-catalog.mjs).\n-- The signature on each row covers the manifest_json beside it; verify\n-- against connectors/catalog.pub.\n',
);
console.log(inserts.join('\n\n'));
