-- Curated connector catalog (PR-26): signed/versioned manifests, permissions,
-- installs, and revocation — the machinery that must work before any paid
-- distribution. The catalog itself is free; there is no price, no checkout,
-- no billing touchpoint anywhere in this migration.
--
-- Trust model, stated plainly:
-- - `connector_manifests.signature` covers `manifest_json` (canonical bytes:
--   sorted keys, no whitespace) and verifies against `signer`, the base64 DER
--   of the Ed25519 public key that signed it. Verification is what ships; key
--   custody is the owner's job (see lib/catalog/signing.ts).
-- - `connector_permissions` is the manifest's requested permissions
--   denormalized for querying. The vocabulary is closed — see
--   CATALOG_PERMISSIONS in lib/catalog/manifest.ts.
-- - `connector_installs.granted_permissions` is the JSON array the user
--   explicitly granted at install time. It must always be a subset of the
--   manifest's permissions; the route layer enforces that, and updates that
--   widen permissions are refused until the user re-grants.
-- - Revocation never deletes. It flips `status` to 'revoked': existing
--   installs keep working, new installs are refused, and the UI shows the
--   revoked state honestly.

CREATE TABLE connector_manifests (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  version TEXT NOT NULL,
  manifest_json TEXT NOT NULL,
  signature TEXT NOT NULL,
  signer TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX connector_manifests_name_version ON connector_manifests (name, version);
CREATE INDEX connector_manifests_status ON connector_manifests (status);

CREATE TABLE connector_permissions (
  manifest_id TEXT NOT NULL REFERENCES connector_manifests (id),
  permission TEXT NOT NULL,
  PRIMARY KEY (manifest_id, permission)
);

CREATE TABLE connector_installs (
  user_id TEXT NOT NULL,
  manifest_id TEXT NOT NULL REFERENCES connector_manifests (id),
  granted_permissions TEXT NOT NULL,
  installed_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (user_id, manifest_id)
);
CREATE INDEX connector_installs_user ON connector_installs (user_id);

